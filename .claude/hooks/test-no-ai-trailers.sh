#!/bin/bash
# Test for no-ai-trailers.sh. Usage: .claude/hooks/test-no-ai-trailers.sh
HOOK="$(cd "$(dirname "$0")" && pwd)/no-ai-trailers.sh"
TMP=$(mktemp -d)
trap 'rm -rf "$TMP"' EXIT
FAILS=0

# check <accept|reject> <name> <message text, printf-style>
check() {
  printf "$3" > "$TMP/msg"
  sh "$HOOK" "$TMP/msg" >/dev/null 2>&1
  rc=$?
  if { [ "$1" = reject ] && [ $rc -ne 0 ]; } || { [ "$1" = accept ] && [ $rc -eq 0 ]; }; then
    echo "PASS  $1  $2"
  else
    echo "FAIL  $1  $2 (exit $rc)"; FAILS=$((FAILS + 1))
  fi
}

check reject "claude noreply" 'chore: x\n\nCo-Authored-By: Claude <noreply@anthropic.com>\n'
check reject "claude with model name" 'chore: x\n\nCo-Authored-By: Claude Opus 4 <a@b.c>\n'
check reject "Claude (AI)" 'chore: x\n\nCo-Authored-By: Claude (AI) <a@b.c>\n'
check reject "sonnet foreign email" 'chore: x\n\nCo-Authored-By: Sonnet 5.5 <a@b.c>\n'
check reject "fable" 'chore: x\n\nCo-Authored-By: Fable <a@b.c>\n'
check reject "haiku" 'chore: x\n\nCo-Authored-By: Haiku <a@b.c>\n'
check reject "copilot" 'chore: x\n\nCo-authored-by: Copilot <a@b.c>\n'
check reject "chatgpt" 'chore: x\n\nCo-authored-by: ChatGPT <a@b.c>\n'
check reject "cursor" 'chore: x\n\nCo-authored-by: Cursor Agent <a@b.c>\n'
check reject "gemini" 'chore: x\n\nCo-authored-by: Gemini <a@b.c>\n'
check reject "plain AI word" 'chore: x\n\nCo-authored-by: AI Helper <a@b.c>\n'
check reject "Assisted-by" 'chore: x\n\nAssisted-by: Claude\n'
check reject "Generated-by trailer" 'chore: x\n\nGenerated-by: Copilot\n'
check reject "Generated by Claude" 'chore: x\n\nGenerated by Claude\n'
check reject "written with help of claude code" 'chore: x\n\nwritten with the help of claude code\n'
check reject "Generated with Copilot" 'chore: x\n\nGenerated with Copilot\n'
check reject "Generated with Claude Code link" 'chore: x\n\nGenerated with [Claude Code](https://claude.com/claude-code)\n'
check reject "robot emoji" 'chore: x\n\n🤖 done\n'
check reject "Claude-Session" 'chore: x\n\nClaude-Session: abc\n'
check reject "leading whitespace" 'chore: x\n\n   co-authored-by: claude <a@b.c>\n'
check reject "upper case" 'chore: x\n\nCO-AUTHORED-BY: CLAUDE <a@b.c>\n'
check reject "CRLF" 'chore: x\r\n\r\nCo-Authored-By: Claude <noreply@anthropic.com>\r\n'
check reject "mid-body trailer" 'chore: x\n\nCo-Authored-By: Claude <a@b.c>\n\nmore text\n'

check accept "countries bot" 'chore: update countries dataset\n\nCo-authored-by: Countries Bot <bot@worldexplorer.local>\n'
check accept "human co-author" 'feat: x\n\nCo-authored-by: Jane Doe <jane@example.com>\n'
check accept "subject with PR number" 'fix: something (#12)\n'
check accept "prose assistant" 'fix: the assistant screen crashes\n\nThe virtual assistant text overflowed.\n'
check accept "prose main" 'fix: merge into main\n\nRebased on main.\n'
check accept "prose maid/said" 'chore: said maid\n'

echo
[ "$FAILS" -eq 0 ] && echo "All tests passed" || echo "$FAILS test(s) failed"
exit "$FAILS"
